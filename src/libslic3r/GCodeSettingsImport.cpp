GCodeSettingsImport import_gcode_settings(const GCodeSettings &settings)
{
    GCodeSettingsImport out;
    out.generator         = settings.generator;
    out.generator_version = settings.generator_version;
    out.from_superslicer  = settings.generator == "SuperSlicer";

    std::map<std::string, std::string> vals;
    for (const auto &[key, value] : settings.values)
        vals[key] = value;
    auto preset_name = [&vals](const char *key) {
        auto it = vals.find(key);
        if (it == vals.end())
            return std::string();
        // filament_settings_id is a list of quoted names.
        ConfigOptionStrings names;
        if (boost::starts_with(it->second, "\"") && names.deserialize(it->second) && ! names.values.empty())
            return names.values.front();
        return it->second;
    };
    out.printer_name  = preset_name("printer_settings_id");
    out.print_name    = preset_name("print_settings_id");
    out.filament_name = preset_name("filament_settings_id");

    // Values to load: converted ones for SuperSlicer, the file's otherwise.
    std::vector<std::pair<std::string, std::string>> to_load;
    std::set<std::string>                            taken;
    if (out.from_superslicer) {
        SuperSlicerConverter conv(vals, out.notes);
        conv.run();
        to_load.assign(conv.out.begin(), conv.out.end());
        taken = std::move(conv.taken);
    } else
        to_load = settings.values;

    ConfigSubstitutionContext ctxt(ForwardCompatibilitySubstitutionRule::Enable);
    for (auto [key, value] : to_load) {
        const std::string orig_key = key, orig_value = value;
        PrintConfigDef::handle_legacy(key, value);
        if (key.empty()) {
            out.not_imported.emplace_back(orig_key + " = " + orig_value);
            continue;
        }
        try {
            out.config.set_deserialize(key, value, ctxt);
        } catch (const UnknownOptionException &) {
            out.not_imported.emplace_back(orig_key + " = " + orig_value);
            continue;
        } catch (const BadOptionValueException &) {
            // Not substituted (graphs, ...): the preset keeps its value, the G-code still opens.
            out.invalid.emplace_back(orig_key + " = " + orig_value);
            // set_deserialize() created the option before failing.
            out.config.erase(key);
            continue;
        }
        // An empty list where values are required (stock ConfigOptionEnums::serialize() drops the first value, so G-code
        // sliced from the default config has "cooling_slowdown_logic = "): keep the preset's value.
        const ConfigOption    *opt = out.config.option(key);
        const ConfigOptionDef *def = print_config_def.get(key);
        if (opt->is_vector() && opt->type() != coStrings && static_cast<const ConfigOptionVectorBase*>(opt)->empty() &&
            def->default_value && def->default_value->is_vector() &&
            ! static_cast<const ConfigOptionVectorBase*>(def->default_value.get())->empty()) {
            out.invalid.emplace_back(orig_key + " = " + orig_value);
            out.config.erase(key);
        }
    }
    if (out.from_superslicer)
        for (const auto &[key, value] : settings.values)
            if (! taken.count(key) && print_config_def.get(key) == nullptr &&
                key != "print_settings_id" && key != "filament_settings_id" && key != "printer_settings_id")
                out.not_imported.emplace_back(key + " = " + value);
    out.config.handle_legacy_composite();
    // Values that could not be read: keep the preset's value rather than the default the substitution put in.
    for (const ConfigSubstitution &s : ctxt.substitutions) {
        out.invalid.emplace_back(s.opt_def->opt_key + " = " + s.old_value);
        out.config.erase(s.opt_def->opt_key);
    }
    std::sort(out.not_imported.begin(), out.not_imported.end());
    return out;
}


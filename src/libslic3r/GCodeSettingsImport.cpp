// ---- Reading the settings block ----

bool parse_key_value(const std::string &line, std::string &key, std::string &value)
{
    // "; key = value"
    const size_t pos = line.find('=');
    if (pos == std::string::npos || pos < 2 || line.front() != ';')
        return false;
    key   = line.substr(1, pos - 1);
    value = line.substr(pos + 1);
    boost::trim(key);
    boost::trim(value);
    return ! key.empty();
}

GCodeSettings read_binary_gcode_settings(const std::string &path, FILE &file)
{
    using namespace bgcode::core;
    using namespace bgcode::binarize;
    std::vector<std::byte> cs_buffer(65536);
    FileHeader file_header;
    EResult res = read_header(file, file_header, nullptr);
    if (res != EResult::Success)
        throw RuntimeError(format("Error while reading file %1%: %2%", path, std::string(translate_result(res))));
    BlockHeader block_header;
    res = read_next_block_header(file, file_header, block_header, EBlockType::SlicerMetadata, cs_buffer.data(), cs_buffer.size());
    if (res != EResult::Success || EBlockType(block_header.type) != EBlockType::SlicerMetadata)
        throw RuntimeError(format("No settings found in %1%", path));
    SlicerMetadataBlock block;
    res = block.read_data(file, file_header, block_header);
    if (res != EResult::Success)
        throw RuntimeError(format("Error while reading file %1%: %2%", path, std::string(translate_result(res))));
    GCodeSettings out;
    // Binary G-code is only written by PrusaSlicer.
    out.generator = "PrusaSlicer";
    out.values    = block.raw_data;
    return out;
}


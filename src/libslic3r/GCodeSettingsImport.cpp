std::string first_item(const std::string &v)
{
    return v.substr(0, v.find(','));
}

std::string fmt_g(double v, const char *f = "%g")
{
    char buf[64];
    snprintf(buf, sizeof(buf), f, v);
    return buf;
}

bool is_vector_type(ConfigOptionType t)
{
    return t == coInts || t == coFloats || t == coBools || t == coPercents || t == coFloatsOrPercents || t == coStrings;
}

class SuperSlicerConverter
{
public:
    SuperSlicerConverter(const std::map<std::string, std::string> &vals, std::vector<std::string> &notes) : vals(vals), notes(notes) {}

    // Converted options, and the SuperSlicer-only options used for them.
    std::map<std::string, std::string> out;
    std::set<std::string>              taken;

    void run()
    {
        for (const auto &[key, value] : vals) {
            if (key == "print_settings_id" || key == "filament_settings_id" || key == "printer_settings_id" || key == "inherits")
                continue;
            if (print_config_def.get(key) == nullptr)
                continue;
            if (std::optional<std::string> v = convert_value(key, value))
                out[key] = *v;
            taken.insert(key);
        }
        map_print();
        map_filament();
        map_printer();
    }

private:
    const std::map<std::string, std::string> &vals;
    std::vector<std::string>                 &notes;

    void note(const std::string &s) { notes.emplace_back(s); }
    const std::string *get(const std::string &key) const { auto it = vals.find(key); return it == vals.end() ? nullptr : &it->second; }
    void take(const std::string &key) { taken.insert(key); }

    double nozzle() const
    {
        const std::string *v = get("nozzle_diameter");
        return v ? std::atof(first_item(*v).c_str()) : 0.4;
    }

    // Absolute value of a SuperSlicer float-or-percent option, following the SuperSlicer chain of percentages.
    std::optional<double> resolve_abs(const std::string &key, int depth = 0) const
    {
        if (depth > 6)
            return {};
        if (key == "nozzle_diameter")
            return nozzle();
        const std::string *pv = get(key);
        if (pv == nullptr || boost::starts_with(*pv, "!"))
            return {};
        const std::string v = first_item(*pv);
        if (! boost::ends_with(v, "%")) {
            char *end = nullptr;
            const double d = std::strtod(v.c_str(), &end);
            return end != v.c_str() ? std::optional<double>(d) : std::nullopt;
        }
        auto it = ss_percent.find(key);
        if (it == ss_percent.end() || it->second.ratio_over == nullptr || std::string(it->second.ratio_over) == "depends")
            return {};
        std::optional<double> base = resolve_abs(it->second.ratio_over, depth + 1);
        if (! base)
            return {};
        return std::atof(v.c_str()) / 100. * *base;
    }

    std::optional<std::string> convert_value(const std::string &key, const std::string &v)
    {
        const ConfigOptionDef *def = print_config_def.get(key);
        const ConfigOptionType typ = def->type;
        // Graphs (dynamic overhangs): same format, the "!" (disabled) mark is an enable option here (map_print / map_filament).
        if (typ == coGraph || typ == coGraphs) {
            std::string s = v;
            s.erase(std::remove(s.begin(), s.end(), '!'), s.end());
            return s;
        }
        // Converted by map_print.
        if (key == "overhangs_width_speed")
            return {};
        // Disabled values.
        if (v.find('!') != std::string::npos && typ != coString && typ != coStrings) {
            if (ss_fan_keys.count(key)) {
                std::vector<std::string> items;
                boost::split(items, v, boost::is_any_of(","));
                for (std::string &x : items)
                    if (boost::starts_with(x, "!"))
                        x = "-1";
                return boost::join(items, ",");
            }
            if (auto it = ss_disabled_to.find(key); it != ss_disabled_to.end())
                return it->second;
            if (boost::starts_with(key, "filament_") && def->nullable)
                return std::string("nil");
            note(format("%1% = %2%: disabled in SuperSlicer, kept from the preset", key, v));
            return {};
        }
        // Percentages computed over another option in SuperSlicer.
        if (v.find('%') != std::string::npos && typ != coString && typ != coStrings) {
            if (auto it = ss_percent.find(key); it != ss_percent.end() && it->second.convert) {
                const bool pct_here = typ == coFloatOrPercent || typ == coFloatsOrPercents || typ == coPercent || typ == coPercents;
                if (it->second.ratio_over && std::string(it->second.ratio_over) == "depends" && pct_here &&
                    key.find("acceleration") == std::string::npos)
                    // A percentage of the feature speed in both. Not the first layer acceleration: a percentage of the
                    // default acceleration here.
                    return v;
                if (it->second.type == 'p' && (typ == coFloat || typ == coFloats)) {
                    std::vector<std::string> items;
                    boost::split(items, v, boost::is_any_of(","));
                    for (std::string &x : items)
                        x = fmt_g(std::atof(x.c_str()) / 100.);
                    return boost::join(items, ",");
                }
                std::optional<double> a = resolve_abs(key);
                if (! a) {
                    note(format("%1% = %2%: percentage could not be resolved, kept from the preset", key, v));
                    return {};
                }
                const std::string r = fmt_g(*a, "%.4g");
                note(format("%1% = %2% -> %3% (SuperSlicer computes the percentage over %4%)", key, v, r,
                            it->second.ratio_over ? it->second.ratio_over : "nozzle_diameter"));
                return r;
            }
        }
        // Enums.
        std::string mapped = v;
        if (auto it = ss_enum_map.find(key); it != ss_enum_map.end())
            if (auto it2 = it->second.find(v); it2 != it->second.end())
                mapped = it2->second;
        if (def->enum_def && def->enum_def->has_values() && (typ == coEnum || typ == coEnums)) {
            std::vector<std::string> items;
            boost::split(items, mapped, boost::is_any_of(typ == coEnums ? "," : ";"));
            const std::vector<std::string> &known = def->enum_def->values();
            const bool ok = mapped.empty() || std::all_of(items.begin(), items.end(),
                [&known](const std::string &x) { return std::find(known.begin(), known.end(), x) != known.end(); });
            if (! ok) {
                note(format("%1% = %2%: value unknown here, kept from the preset", key, v));
                return {};
            }
        }
        if (mapped != v) {
            note(format("%1% = %2% -> %3%", key, v, mapped));
            return mapped;
        }
        // Floats -> ints (layer time thresholds).
        if ((typ == coInts || typ == coInt) && v.find('.') != std::string::npos &&
            std::all_of(v.begin(), v.end(), [](char c) { return std::isdigit((unsigned char)c) || c == '-' || c == '.' || c == ','; })) {
            std::vector<std::string> items;
            boost::split(items, v, boost::is_any_of(","));
            for (std::string &x : items)
                x = std::to_string(int(std::lround(std::atof(x.c_str()))));
            return boost::join(items, ",");
        }
        return v;
    }

    void map_print()
    {
        if (const std::string *c = get("first_layer_size_compensation"); c && ! boost::starts_with(*c, "!")) {
            out["elefant_foot_compensation"] = fmt_g(std::max(0., -std::atof(c->c_str())));
            note(format("first_layer_size_compensation = %1% -> elefant_foot_compensation = %2%", *c, out["elefant_foot_compensation"]));
        }
        take("first_layer_size_compensation");
        if (const std::string *v = get("only_one_perimeter_top")) {
            out["top_one_perimeter_type"] = *v == "1" ? "top" : "none";
            take("only_one_perimeter_top");
        }
        if (const std::string *p = get("support_material_top_interface_pattern")) {
            const ConfigOptionDef *def = print_config_def.get("support_material_interface_pattern");
            const std::vector<std::string> &known = def->enum_def->values();
            out["support_material_interface_pattern"] = std::find(known.begin(), known.end(), *p) != known.end() ? *p : "auto";
            take("support_material_top_interface_pattern");
        }
        // Brim: brim_type here instead of an interior brim width.
        if (get("brim_width") || get("brim_width_interior")) {
            const double bw = resolve_abs("brim_width").value_or(0.);
            const double bi = resolve_abs("brim_width_interior").value_or(0.);
            out["brim_type"] = bw > 0 && bi > 0 ? "outer_and_inner" : bi > 0 ? "inner_only" : bw > 0 ? "outer_only" : "no_brim";
            if (bi > 0) {
                out["brim_width"] = fmt_g(std::max(bw, bi));
                note(format("interior brim %1% mm: one brim width for the inner and the outer brim here", fmt_g(bi)));
            }
            take("brim_width_interior");
        }
        // Per feature accelerations: 0 falls back to a parent feature in SuperSlicer, to the stock acceleration here: the
        // parent's value (a percentage here is of the default acceleration).
        for (const auto &[key, parent] : { std::pair<const char*, const char*>{ "gap_fill_acceleration", "perimeter_acceleration" },
                                           { "ironing_acceleration", "top_solid_infill_acceleration" },
                                           { "brim_acceleration", "support_material_acceleration" } })
            if (const std::string *v = get(key); v && *v == "0")
                if (const std::optional<double> a = resolve_abs(parent); a && *a > 0.) {
                    out[key] = fmt_g(*a, "%.4g");
                    note(format("%1% = 0 -> %2% (SuperSlicer: 0 = the %3%)", key, out[key], parent));
                }
        // Widths set as a spacing in SuperSlicer: the width is written empty. Width at the print layer height, as SuperSlicer's
        // Flow::new_from_config(): spacing + layer_height * (1 - pi/4) * overlap; the external perimeter spacing is a half
        // spacing (overlap - 0.5). Spacing 0 = auto width (0 here too).
        {
            auto ratio = [this](const char *key) {
                const std::string *v = get(key);
                return v == nullptr || v->empty() || boost::starts_with(*v, "!") ? 1. :
                       std::atof(first_item(*v).c_str()) / (boost::ends_with(first_item(*v), "%") ? 100. : 1.);
            };
            const double max_overlap = ratio("filament_max_overlap");
            for (const auto &[width_key, spacing_key, overlap_key] : std::initializer_list<std::tuple<const char*, const char*, const char*>> {
                     { "extrusion_width", "extrusion_spacing", nullptr },
                     { "external_perimeter_extrusion_width", "external_perimeter_extrusion_spacing", "external_perimeter_overlap" },
                     { "perimeter_extrusion_width", "perimeter_extrusion_spacing", "perimeter_overlap" },
                     { "infill_extrusion_width", "infill_extrusion_spacing", nullptr },
                     { "solid_infill_extrusion_width", "solid_infill_extrusion_spacing", "solid_infill_overlap" },
                     { "top_infill_extrusion_width", "top_infill_extrusion_spacing", nullptr },
                     { "first_layer_extrusion_width", "first_layer_extrusion_spacing", nullptr } }) {
                take(spacing_key);
                const std::string *w = get(width_key);
                const std::string *s = get(spacing_key);
                if (w == nullptr || ! w->empty() || s == nullptr || s->empty())
                    continue;
                const double spacing = boost::ends_with(*s, "%") ? std::atof(s->c_str()) / 100. * nozzle() : std::atof(s->c_str());
                if (spacing <= 0.) {
                    out[width_key] = "0";
                    continue;
                }
                const bool   first_layer  = boost::starts_with(width_key, "first_layer_");
                const double layer_height = resolve_abs(first_layer ? "first_layer_height" : "layer_height").value_or(0.2);
                const double rounding     = layer_height * (1. - 0.25 * PI);
                const double overlap      = overlap_key ? std::min(ratio(overlap_key), max_overlap) : std::min(1., max_overlap);
                const double width        = spacing + rounding * (std::string(width_key) == "external_perimeter_extrusion_width" ? overlap - 0.5 : overlap);
                out[width_key] = fmt_g(width, "%.4g");
                note(format("%1% = %2% -> %3% = %4% (SuperSlicer width from the spacing at layer height %5%)", spacing_key, *s,
                            width_key, out[width_key], fmt_g(layer_height)));            }
        }
        if (const std::string *v = get("small_perimeter_min_length"); v && *v == "0") {
            out["small_perimeter_min_length"] = "0.001";
            note("small_perimeter_min_length = 0 -> 0.001 (SuperSlicer: 0 = no small perimeters, here: 0 = stock threshold)");
        }
        if (const std::string *v = get("brim_speed"); v && *v == "0")
            note("brim_speed = 0 is autospeed in SuperSlicer, the support material speed here");
        // Dynamic overhangs: SuperSlicer's dynamic speed is only active with an overhang speed threshold.
        if (get("overhangs_dynamic_speed") || get("overhangs_width_speed")) {
            const std::string *dyn = get("overhangs_dynamic_speed");
            const std::string *thr = get("overhangs_width_speed");
            out["enable_dynamic_overhang_speeds"] = (! dyn || boost::starts_with(*dyn, "!") || ! thr || boost::starts_with(*thr, "!")) ? "0" : "1";
            take("overhangs_width_speed");
        }
        // Infill directions: SuperSlicer "Rotate with object" = align to model.
        if (const std::string *v = get("fill_angle_follow_model")) {
            out["align_infill_direction_to_model"] = *v;
            take("fill_angle_follow_model");
        }
        if (const std::string *v = get("fill_angle_cross")) {
            if (*v == "0") {
                out["rotate_solid_infill_direction"] = "0";
                note("fill_angle_cross = 0 -> rotate_solid_infill_direction = 0 (sparse infill still alternates)");
            }
            take("fill_angle_cross");
        }
        // Small area flow compensation: SuperSlicer graph "[!]begin:end:type:x0xy0:x1xy1:..." -> enable flag + "length,factor" lines.
        if (const std::string *g = get("small_area_infill_flow_compensation_model")) {
            const bool enabled = ! boost::starts_with(*g, "!");
            std::vector<std::string> fields;
            boost::split(fields, boost::trim_left_copy_if(*g, boost::is_any_of("!")), boost::is_any_of(":"));
            std::vector<std::string> points;
            for (size_t i = 3; i < fields.size(); ++ i)
                if (size_t x = fields[i].find('x'); x != std::string::npos)
                    points.emplace_back(fields[i].substr(0, x) + "," + fields[i].substr(x + 1));
            out["small_area_infill_flow_compensation"] = enabled ? "1" : "0";
            if (! points.empty())
                out["small_area_infill_flow_compensation_model"] = boost::join(points, "\\n");
            take("small_area_infill_flow_compensation_model");
        }
        if (const std::string *v = get("avoid_bed_notches"); v && *v == "1")
            note("avoid_bed_notches = 1: bed keep-out zones are a printer setting here, kept from the printer preset");
    }

    void map_filament()
    {
        if (const std::string *d = get("default_fan_speed"); d && ! boost::starts_with(*d, "!")) {
            // SuperSlicer default_fan_speed is aliased to min_fan_speed; keep them consistent for the GUI.
            out["min_fan_speed"] = *d;
            out["fan_always_on"] = std::atoi(first_item(*d).c_str()) > 0 ? "1" : "0";
        }
        // SuperSlicer has no cooling switch, the layer time thresholds drive it.
        out["cooling"] = "1";
        // Dynamic overhang fan: the "!" of each graph is the switch.
        if (const std::string *dyn = get("overhangs_dynamic_fan_speed")) {
            std::vector<std::string> graphs;
            boost::split(graphs, *dyn, boost::is_any_of(","));
            for (std::string &g : graphs)
                g = boost::starts_with(g, "!") ? "0" : "1";
            out["enable_dynamic_fan_speeds"] = boost::join(graphs, ",");
        } else
            out["enable_dynamic_fan_speeds"] = "0";
        // SuperSlicer: 99.5% if the part measures 99.5 mm instead of 100 mm. Here: 0.5% for the same part.
        if (const std::string *sh = get("filament_shrink"); sh && boost::ends_with(*sh, "%") && ! boost::starts_with(*sh, "!")) {
            const double xy = std::round((100. - std::atof(sh->c_str())) * 1e4) / 1e4;
            out["filament_shrinkage_compensation_xy"] = fmt_g(xy) + "%";
            if (xy != 0)
                note(format("filament_shrink = %1% -> filament_shrinkage_compensation_xy = %2%", *sh, out["filament_shrinkage_compensation_xy"]));
            take("filament_shrink");
        }
        if (const std::string *pa = get("filament_pressure_advance"); pa && ! boost::starts_with(*pa, "!"))
            note(format("pressure advance %1% is enabled in SuperSlicer but not converted: put SET_PRESSURE_ADVANCE ADVANCE=%1% "
                        "in the filament start G-code if you want it", *pa));
    }

    void map_printer()
    {
        if (const std::string *t = get("thumbnails")) {
            const std::string *f   = get("thumbnails_format");
            const std::string  fmt = f ? *f : "PNG";
            std::vector<std::string> sizes, items;
            boost::split(sizes, *t, boost::is_any_of(","));
            // SuperSlicer uses 0x0 for "no thumbnail".
            for (std::string &s : sizes)
                if (boost::trim_copy(s) != "" && boost::trim_copy(s) != "0x0")
                    items.emplace_back(boost::trim_copy(s) + "/" + fmt);
            out["thumbnails"] = boost::join(items, ", ");
            out.erase("thumbnails_format");
        }
        for (const char *gkey : { "start_gcode", "end_gcode", "before_layer_gcode", "layer_gcode", "toolchange_gcode", "between_objects_gcode",
                                  "color_change_gcode", "pause_print_gcode", "template_custom_gcode" })
            if (auto it = out.find(gkey); it != out.end())
                it->second = fix_gcode(gkey, it->second);
    }

    std::string fix_gcode(const std::string &key, const std::string &g)
    {
        std::string s = std::regex_replace(g, std::regex(R"(\+\s*extruder_temperature_offset\[\w+\])"), "");
        if (s != g)
            note(format("%1%: removed +extruder_temperature_offset[...] (SuperSlicer only)", key));
        // Vector variables without an index inside {} are refused here, SuperSlicer tolerates them.
        {
            // Spaces allowed: "{first_layer_temperature + extruder_temperature_offset[0]}" leaves "{first_layer_temperature }".
            static const std::regex re(R"(\{\s*([a-z_0-9]+)\s*\})");
            std::string res;
            auto last = s.cbegin();
            for (std::sregex_iterator it(s.begin(), s.end(), re), end; it != end; ++ it) {
                const std::string name = (*it)[1];
                res.append(last, (*it)[0].first);
                const ConfigOptionDef *def = print_config_def.get(name);
                if (def && is_vector_type(def->type)) {
                    note(format("%1%: %2% is a per-filament list here, now %2%[initial_extruder]", key, name));
                    res += "{" + name + "[initial_extruder]}";
                } else
                    res += (*it)[0].str();
                last = (*it)[0].second;
            }
            res.append(last, s.cend());
            s = std::move(res);
        }
        if (key == "before_layer_gcode" && std::regex_search(s, std::regex(R"(\blayer_num\b)"))) {
            // SuperSlicer: layer_num is the layer just printed (-1 before the first layer). Here: the layer about to be printed.
            static const std::regex block(R"(\{[^{}]*\}|\[[^\[\]]*\])");
            static const std::regex layer_num(R"(\blayer_num\b)");
            std::string res;
            auto last = s.cbegin();
            for (std::sregex_iterator it(s.begin(), s.end(), block), end; it != end; ++ it) {
                res.append(last, (*it)[0].first);
                res += std::regex_replace((*it)[0].str(), layer_num, "(layer_num-1)");
                last = (*it)[0].second;
            }
            res.append(last, s.cend());
            s = std::move(res);
            note("before_layer_gcode: layer_num -> (layer_num-1) so it counts as in SuperSlicer (layer_z is the upcoming layer here, "
                 "and this G-code is not run before the first layer)");
        }
        return s;
    }
};


GCodeSettings read_gcode_settings(const std::string &path)
{
    {
        FILE *file = boost::nowide::fopen(path.c_str(), "rb");
        if (file == nullptr)
            throw RuntimeError(format("Error opening file %1%", path));
        std::vector<std::byte> cs_buffer(65536);
        const bool binary = bgcode::core::is_valid_binary_gcode(*file, true, cs_buffer.data(), cs_buffer.size()) == bgcode::core::EResult::Success;
        if (binary) {
            fseek(file, 0, SEEK_SET);
            try {
                GCodeSettings out = read_binary_gcode_settings(path, *file);
                fclose(file);
                return out;
            } catch (...) {
                fclose(file);
                throw;
            }
        }
        fclose(file);
    }

    boost::nowide::ifstream ifs(path, std::ifstream::binary);
    GCodeSettings out;
    // The "; generated by" header, at the top unless a post-processing script added lines before it.
    {
        static const std::string header = "; generated by ";
        std::string line;
        for (int i = 0; i < 1000 && std::getline(ifs, line); ++ i)
            if (boost::starts_with(line, header)) {
                std::vector<std::string> words;
                boost::split(words, line.substr(header.size()), boost::is_any_of(" "), boost::token_compress_on);
                if (! words.empty())
                    out.generator = words.front();
                if (words.size() > 1)
                    out.generator_version = words[1];
                break;
            }
    }

    // The settings block is near the end (the thumbnails may follow it): read the tail, the whole file if needed.
    ifs.clear();
    ifs.seekg(0, std::ios::end);
    const std::streamoff length = ifs.tellg();
    std::string text;
    for (std::streamoff tail : { std::streamoff(4) << 20, length }) {
        tail = std::min(tail, length);
        text.assign(size_t(tail), '\0');
        ifs.seekg(length - tail, std::ios::beg);
        ifs.read(text.data(), tail);
        // PrusaSlicer 2.4+ and this fork: "prusaslicer_config", SuperSlicer: "SuperSlicer_config".
        for (const char *name : { "prusaslicer_config", "SuperSlicer_config" }) {
            const std::string begin = std::string("; ") + name + " = begin";
            const std::string end   = std::string("; ") + name + " = end";
            const size_t      b     = text.rfind(begin);
            if (b == std::string::npos)
                continue;
            const size_t e = text.find(end, b);
            if (e == std::string::npos)
                continue;
            std::vector<std::string> lines;
            boost::split(lines, text.substr(b + begin.size(), e - b - begin.size()), boost::is_any_of("\n"));
            std::string key, value;
            for (std::string &line : lines) {
                if (! line.empty() && line.back() == '\r')
                    line.pop_back();
                if (parse_key_value(line, key, value))
                    out.values.emplace_back(key, value);
            }
            if (out.generator.empty())
                out.generator = boost::starts_with(name, "SuperSlicer") ? "SuperSlicer" : "PrusaSlicer";
            return out;
        }
        if (tail == length)
            break;
    }
    // No delimiters (Slic3r, PrusaSlicer before 2.4, older SuperSlicer): "; key = value" lines at the end of the file,
    // read backwards as stock ConfigBase::load_from_gcode_string_legacy(), past the thumbnails if they follow them.
    {
        std::vector<std::string> lines;
        boost::split(lines, text, boost::is_any_of("\n"));
        auto it = lines.rbegin();
        auto blank = [](std::string &l) { boost::trim_right(l); return l.empty() || l == ";"; };
        for (;;) {
            for (; it != lines.rend() && blank(*it); ++ it) ;
            // One thumbnail block per size ("; thumbnail end" ... "; thumbnail begin", also QOI / JPG).
            if (it == lines.rend() || ! (boost::starts_with(*it, "; thumbnail") && boost::ends_with(*it, " end")))
                break;
            for (; it != lines.rend() && ! (boost::starts_with(*it, "; thumbnail") && boost::contains(*it, " begin ")); ++ it) ;
            if (it != lines.rend())
                ++ it;
        }
        std::vector<std::pair<std::string, std::string>> values;
        std::string key, value;
        for (; it != lines.rend(); ++ it) {
            boost::trim_right(*it);
            if (! parse_key_value(*it, key, value) || ! std::isalpha((unsigned char)key.front()) ||
                ! std::all_of(key.begin(), key.end(), [](char c) { return std::isalnum((unsigned char)c) || c == '_'; }))
                break;
            values.emplace_back(key, value);
        }
        // As stock: fewer values is not a settings block.
        if (values.size() >= 80) {
            out.values.assign(values.rbegin(), values.rend());
            if (out.generator.empty())
                out.generator = "PrusaSlicer";
            return out;
        }
    }
    throw RuntimeError(format("No settings found in %1%", path));
}


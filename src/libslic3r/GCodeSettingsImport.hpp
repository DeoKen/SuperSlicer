#ifndef slic3r_GCodeSettingsImport_hpp_
#define slic3r_GCodeSettingsImport_hpp_

// Fork: settings stored at the end of a G-code file, read back to be loaded over the presets of a new SuperPSlicer
// window ("Open settings in SuperPSlicer" in the G-code viewer). SuperSlicer G-code is converted with the rules of
// the bundle converter (SuperSlicer defaults and meaning for the ported features, PrusaSlicer's otherwise).

#include <string>
#include <utility>
#include <vector>

#include "PrintConfig.hpp"

namespace Slic3r {

struct GCodeSettings
{
    // "PrusaSlicer", "SuperSlicer", ... from the "; generated by" header line.
    std::string                                       generator;
    std::string                                       generator_version;
    // Key / value pairs of the settings block, as written in the file.
    std::vector<std::pair<std::string, std::string>>  values;
};

// Throws Slic3r::RuntimeError if the file has no settings block.
GCodeSettings read_gcode_settings(const std::string &path);

struct GCodeSettingsImport
{
    std::string                generator;
    std::string                generator_version;
    bool                       from_superslicer { false };
    // Settings known to this fork, converted. Values that could not be read are left out (see invalid).
    DynamicPrintConfig         config;
    // Names of the presets the G-code was sliced with (may be empty or unknown here).
    std::string                printer_name;
    std::string                print_name;
    std::string                filament_name;
    // "key = value" of the settings this fork does not have.
    std::vector<std::string>   not_imported;
    // "key = value" of the settings whose value this fork cannot read.
    std::vector<std::string>   invalid;
    // Conversions made from SuperSlicer values.
    std::vector<std::string>   notes;
};

GCodeSettingsImport import_gcode_settings(const GCodeSettings &settings);
inline GCodeSettingsImport import_gcode_settings(const std::string &path) { return import_gcode_settings(read_gcode_settings(path)); }

} // namespace Slic3r

#endif // slic3r_GCodeSettingsImport_hpp_

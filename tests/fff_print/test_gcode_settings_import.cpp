std::string write_temp(const std::string &text)
{
    const auto path = boost::filesystem::temp_directory_path() / boost::filesystem::unique_path("gcode-settings-%%%%-%%%%.gcode");
    boost::nowide::ofstream f(path.string(), std::ios::binary);
    f << text;
    return path.string();
}

GCodeSettingsImport import_text(const std::string &text)
{
    const std::string path = write_temp(text);
    GCodeSettingsImport imp = import_gcode_settings(path);
    boost::filesystem::remove(path);
    return imp;
}

bool has_line(const std::vector<std::string> &lines, const std::string &start)
{
    return std::any_of(lines.begin(), lines.end(), [&start](const std::string &l) { return l.rfind(start, 0) == 0; });
}


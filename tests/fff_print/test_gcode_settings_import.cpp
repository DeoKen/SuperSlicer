// SuperSlicer G-code: header, a few moves, the settings, then the thumbnails (thumbnails_end_file) if asked.
std::string superslicer_gcode(const std::string &settings, bool delimiters, bool thumbnails_at_end)
{
    std::string thumbnails;
    if (thumbnails_at_end)
        for (const char *size : { "64x64 3560", "400x300 100000" }) {
            thumbnails += std::string(";\n; thumbnail begin ") + size + "\n";
            for (int i = 0; i < 700; ++ i)
                thumbnails += "; " + std::string(78, 'A') + "\n";
            thumbnails += "; thumbnail end\n;\n";
        }
    return "; generated by SuperSlicer 2.7.62.0-beta2-2026-08-07 on 2026-09-21 at 23:47:25 UTC\n"
           "G1 X10 Y10 E1\nG1 X20 Y10 E2\n" +
           (delimiters ? "; SuperSlicer_config = begin\n" + settings + "; SuperSlicer_config = end\n" : settings) + thumbnails;
}


    CHECK_FALSE(imp.from_superslicer);
    CHECK(imp.not_imported.empty());
    CHECK(imp.invalid.empty());
    CHECK(imp.config.opt_serialize("cooling_slowdown_logic") == "uniform_cooling");
    CHECK(imp.config.opt_int("perimeters") == 5);
    CHECK(imp.config.option<ConfigOptionPercent>("fill_density")->value == Approx(35.));
    CHECK(imp.config.option<ConfigOptionFloats>("nozzle_diameter")->values.front() == Approx(0.6));
    CHECK(imp.config.option<ConfigOptionInts>("bridge_fan_speed")->values.front() == 77);

        CHECK(imp.config.opt_serialize("idle_temperature") == "nil");
        CHECK(imp.config.opt_serialize("first_layer_infill_speed") == "0");
        CHECK(imp.config.opt_serialize("first_layer_extrusion_width") == "0");
